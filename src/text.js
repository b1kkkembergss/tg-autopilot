// Разбор реплик собеседницы: закрывает ли она разговор.
// Отвечать на «на связи» / «побежала» / «ок» — навязчиво и выдаёт бота.

// Короткие фразы, которыми разговор заканчивают.
const CLOSING_PATTERNS = [
  /^(на связи|на связи\)|на связи!)$/i,
  /^(ок|окей|ok|okay|ага|угу|да|нет|понял|поняла|понятно|ясно|хорошо|ладно|договорились|принял|приняла)[).!]*$/i,
  /^(есть,? капитан|так точно|есть)[).!]*$/i,
  /^(побежал|побежала|убегаю|ушёл|ушла|ушли|пошёл|пошла|спать|до завтра|до вечера|до связи|до встречи|пока|бай|bye|споки|спокойной ночи)[).!]*$/i,
  /^(спасибо|спс|благодарю|thanks|thank you)[).!]*$/i,
  /^(супер|класс|отлично|здорово|круто|вау|ничего себе)[).!]*$/i,
  /^[👍❤️🔥😊🙂😂🤣💋😘🌺✨💯]+$/u,
];

/**
 * true, если сообщение — короткая закрывающая реплика, на которую не надо отвечать.
 * Длинные сообщения (>40 символов) считаются содержательными: даже если начинаются
 * с «ок», дальше идёт мысль, на которую стоит отреагировать.
 */
export function isClosingMessage(text) {
  const t = (text || '').trim();
  if (!t) return true;
  if (t.length > 40) return false;
  return CLOSING_PATTERNS.some((re) => re.test(t));
}

/**
 * Чистит маркеры нейросетевого текста: длинное/среднее тире.
 * Промпт их запрещает, но модель иногда всё равно вставляет — тогда
 * переписываем на живую пунктуацию: запятая или обычный дефис.
 *
 * «привет — как дела» → «привет, как дела»
 * «Москва–Питер»      → «Москва-Питер»
 */
export function humanize(text) {
  let t = (text || '').trim();
  if (!t) return t;
  // Тире между словами → запятая (так в живой переписке чаще всего)
  t = t.replace(/\s+[—–]\s+/g, ', ');
  // Тире с пробелом только с одной стороны
  t = t.replace(/\s+[—–]/g, ',');
  t = t.replace(/[—–]\s+/g, ', ');
  // Оставшиеся тире внутри слов (диапазоны) → дефис
  t = t.replace(/[—–]/g, '-');
  // Прибираем возможные артефакты «, ,» и запятую в начале
  t = t.replace(/,\s*,/g, ',').replace(/^,\s*/, '');
  return t.trim();
}
